#!/usr/bin/env python3
"""
Applied Lab R16-T041: Token-Budget Preflight — Runnable Concept Example.

This module demonstrates token-budget preflight checking and truncation reporting,
connecting directly to the model inputs concept in Chapter 2, Section 3
("Models" [the-models]) of the Hugging Face course.

IMPORTANT TEACHING APPROXIMATION NOTICE:
The tokenizer implemented in this module is a deterministic local whitespace-splitting
fixture (`prompt.strip().split()`). It serves as an educational teaching approximation
to illustrate the tokenization boundary, resource budget, and preflight truncation
reporting. It is NOT the model's real tokenizer (e.g. WordPiece / BPE / Unigram as
introduced in subsequent sections) and does not perform subword segmentation, vocabulary
lookup, or special token insertion ([CLS]/[SEP]).

Contract:
- Configured budget N (integer >= 0).
- Budget 3 with "one two three four" retains ['one', 'two', 'three'] and reports
  1 removed token.
- Empty input retains [] and reports 0 removed tokens.
- Negative budgets (budget < 0) are rejected with ValueError.
- Focus: Implements minimal complete local example and connects public inputs/outputs
  to the lesson concept.
"""

from dataclasses import dataclass
from typing import Any, Dict, List, Optional
import sys

TOKENIZER_NOTE = (
    "[TEACHING APPROXIMATION] This module uses deterministic whitespace tokenization "
    "as an educational proxy to illustrate tokenization boundaries and budget preflights. "
    "It is NOT a production model tokenizer (e.g., WordPiece, BPE) and does not insert "
    "special tokens ([CLS], [SEP]) or handle subword vocabulary IDs."
)


@dataclass(frozen=True)
class PreflightReport:
    """Report generated by a token-budget preflight check."""

    prompt: str
    budget: int
    total_tokens: int
    retained: List[str]
    removed_count: int
    is_truncated: bool

    def as_dict(self) -> Dict[str, Any]:
        """Convert report to dictionary format."""
        return {
            "prompt": self.prompt,
            "budget": self.budget,
            "total_tokens": self.total_tokens,
            "retained": list(self.retained),
            "removed_count": self.removed_count,
            "is_truncated": self.is_truncated,
        }


class TokenBudgetPreflight:
    """Deterministic token-budget preflight checker.

    Attributes:
        budget (int): Configured maximum number of allowed tokens (must be >= 0).
    """

    def __init__(self, budget: int) -> None:
        if not isinstance(budget, int) or isinstance(budget, bool):
            raise TypeError(f"Budget must be an integer, got {type(budget).__name__}")
        if budget < 0:
            raise ValueError(f"Token budget cannot be negative: received {budget}")
        self.budget: int = budget

    def tokenize(self, prompt: str) -> List[str]:
        """Tokenize text using whitespace splitting.

        Teaching approximation: splits on whitespace without subword segmentation.

        Args:
            prompt (str): Text prompt to tokenize.

        Returns:
            List[str]: Extracted whitespace token strings.
        """
        if not isinstance(prompt, str):
            raise TypeError(f"Prompt must be a string, got {type(prompt).__name__}")
        cleaned = prompt.strip()
        if not cleaned:
            return []
        return cleaned.split()

    def check(self, prompt: str) -> PreflightReport:
        """Execute preflight check on prompt and report retained tokens and truncation.

        Args:
            prompt (str): Prompt to check against the configured budget.

        Returns:
            PreflightReport: Detailed report of retained tokens and truncation status.
        """
        tokens = self.tokenize(prompt)
        total = len(tokens)

        if total <= self.budget:
            retained = tokens
            removed = 0
            is_truncated = False
        else:
            retained = tokens[: self.budget]
            removed = total - self.budget
            is_truncated = True

        return PreflightReport(
            prompt=prompt,
            budget=self.budget,
            total_tokens=total,
            retained=retained,
            removed_count=removed,
            is_truncated=is_truncated,
        )


def check_token_budget(prompt: str, budget: int) -> Dict[str, Any]:
    """Functional convenience entrypoint for token-budget preflight check.

    Args:
        prompt (str): Prompt text.
        budget (int): Token budget (must be >= 0).

    Returns:
        Dict[str, Any]: Preflight report dictionary.
    """
    engine = TokenBudgetPreflight(budget)
    return engine.check(prompt).as_dict()


if __name__ == "__main__":
    print("=== Token-Budget Preflight Example (R16-T041) ===")
    print(f"Notice: {TOKENIZER_NOTE}\n")

    # Contract scenario 1: Normal case with truncation
    prompt_sample = "one two three four"
    budget_val = 3
    preflight = TokenBudgetPreflight(budget_val)
    report = preflight.check(prompt_sample)
    print(f"Scenario 1: Prompt='{prompt_sample}', Budget={budget_val}")
    print(f"  Total tokens:   {report.total_tokens}")
    print(f"  Retained tokens:{report.retained}")
    print(f"  Removed tokens: {report.removed_count}")
    print(f"  Is truncated:   {report.is_truncated}\n")

    # Contract scenario 2: Empty input
    report_empty = preflight.check("")
    print(f"Scenario 2: Empty input")
    print(f"  Retained tokens:{report_empty.retained}")
    print(f"  Removed tokens: {report_empty.removed_count}\n")

    # Contract scenario 3: Negative budget rejection
    try:
        TokenBudgetPreflight(-1)
    except ValueError as exc:
        print(f"Scenario 3: Negative budget correctly rejected: {exc}")
